public class Variaveis {
    
    public static void main(String[] args) {
        
        String nome = "Luis";
        char letra = 'L';
        int idade = 30;
        double altura = 1.77;
        boolean estuda = true;

        System.out.println(nome);
        System.out.println(letra);
        System.out.println(idade);
        System.out.println(altura);
        System.out.println(estuda);
    }
}
