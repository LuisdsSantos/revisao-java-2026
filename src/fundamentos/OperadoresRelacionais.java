
public class OperadoresRelacionais {
    
    public static void main(String[] args) {

        int num1 = 10;
        int num2 = 5;

        System.out.println(num1 > num2); // Maior que
        System.out.println(num1 >= num2); // Maior ou igual
        System.out.println(num1 < num2); // Menor que
        System.out.println(num1 <= num2); // Menor ou igual
        System.out.println(num1 == num2); // Igual a
        System.out.println(num1 != num2); // Diferente

    }
}
